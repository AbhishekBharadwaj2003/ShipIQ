
import os
import sqlite3
import sys

import psycopg
from psycopg.rows import dict_row

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SQLITE_PATH = os.path.join(BASE_DIR, "shipiq_data.sqlite3")

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    sys.exit(
        "ERROR: DATABASE_URL is not set. "
        "Set your Supabase PostgreSQL connection string as an environment variable."
    )

TABLES = {
    "shipments": """
        CREATE TABLE IF NOT EXISTS shipments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            brand TEXT,
            manifested_date TEXT,
            shipment_id TEXT,
            payload_json TEXT NOT NULL
        )
    """,
    "shipiq_users": """
        CREATE TABLE IF NOT EXISTS shipiq_users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT,
            email TEXT,
            password_hash TEXT,
            role TEXT,
            is_active INTEGER,
            is_primary_admin INTEGER,
            created_at TEXT,
            updated_at TEXT,
            last_login TEXT
        )
    """,
    "shipiq_audit_logs": """
        CREATE TABLE IF NOT EXISTS shipiq_audit_logs (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            actor_user_id BIGINT,
            action TEXT,
            target_user_id BIGINT,
            details TEXT,
            created_at TEXT
        )
    """,
    "shipiq_login_attempts": """
        CREATE TABLE IF NOT EXISTS shipiq_login_attempts (
            email TEXT PRIMARY KEY,
            failures INTEGER,
            window_start DOUBLE PRECISION,
            locked_until DOUBLE PRECISION
        )
    """,
    "shipiq_metadata": """
        CREATE TABLE IF NOT EXISTS shipiq_metadata (
            key TEXT PRIMARY KEY,
            value TEXT
        )
    """,
}

def main():
    if not os.path.exists(SQLITE_PATH):
        sys.exit(f"ERROR: SQLite database not found: {SQLITE_PATH}")

    source = sqlite3.connect(SQLITE_PATH)
    source.row_factory = sqlite3.Row

    try:
        source_counts = {
            table: source.execute(
                f'SELECT COUNT(*) FROM "{table}"'
            ).fetchone()[0]
            for table in TABLES
        }

        print("SQLite source row counts:")
        for table, count in source_counts.items():
            print(f"  {table}: {count}")

        with psycopg.connect(DATABASE_URL, row_factory=dict_row) as target:
            with target.cursor() as cur:
                for ddl in TABLES.values():
                    cur.execute(ddl)

                # Refuse to append to an existing database or overwrite data.
                existing_counts = {}
                for table in TABLES:
                    cur.execute(f'SELECT COUNT(*) AS n FROM "{table}"')
                    existing_counts[table] = cur.fetchone()["n"]

                if any(existing_counts.values()):
                    raise RuntimeError(
                        "Target tables already contain data. Migration stopped "
                        "to avoid duplicates or overwriting existing records. "
                        f"Target counts: {existing_counts}"
                    )

                for table in TABLES:
                    rows = source.execute(
                        f'SELECT * FROM "{table}" ORDER BY id'
                    ).fetchall() if table not in (
                        "shipiq_login_attempts", "shipiq_metadata"
                    ) else source.execute(
                        f'SELECT * FROM "{table}"'
                    ).fetchall()

                    if not rows:
                        continue

                    columns = rows[0].keys()
                    column_sql = ", ".join(f'"{col}"' for col in columns)
                    placeholders = ", ".join(["%s"] * len(columns))
                    insert_sql = (
                        f'INSERT INTO "{table}" ({column_sql}) '
                        f'VALUES ({placeholders})'
                    )

                    cur.executemany(
                        insert_sql,
                        [tuple(row[col] for col in columns) for row in rows],
                    )

                # Keep identity sequences aligned with imported IDs.
                for table in ("shipments", "shipiq_users", "shipiq_audit_logs"):
                    cur.execute(
                        f"""
                        SELECT setval(
                            pg_get_serial_sequence('{table}', 'id'),
                            COALESCE((SELECT MAX(id) FROM "{table}"), 1),
                            EXISTS (SELECT 1 FROM "{table}")
                        )
                        """
                    )

                # Verify every table before the transaction commits.
                target_counts = {}
                for table in TABLES:
                    cur.execute(f'SELECT COUNT(*) AS n FROM "{table}"')
                    target_counts[table] = cur.fetchone()["n"]

                print("\nSupabase row counts:")
                for table, count in target_counts.items():
                    print(f"  {table}: {count}")

                if source_counts != target_counts:
                    raise RuntimeError(
                        "Row counts do not match. Transaction will roll back. "
                        f"SQLite={source_counts}; Supabase={target_counts}"
                    )

        print("\nMigration completed and row counts verified.")

    finally:
        source.close()

if __name__ == "__main__":
    main()
